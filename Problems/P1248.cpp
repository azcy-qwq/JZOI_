const int N=1e4+10;
mt19937 rnd(time(0));
int n,a[N],b[N],p[N],prvp[N],ans=INT_MAX,prv,cur,ansp[N];
uniform_real_distribution<> rd(0,1);
inline int xrd(){
    return rnd()%n+1;
}inline int calc(){
    int at=0,bt=0;
    for(int i=1;i<=n;++i){
        at+=a[p[i]];
        bt=maxm(at,bt);
        bt+=b[p[i]];
    }return maxm(at,bt);
}
void sa(){
    double t=0.9;
    prv=INT_MAX;
    while(t>0.001){
        for(int i=1;i<=n;++i)
            if(rd(rnd)<t) swap(p[xrd()],p[xrd()]);
        cur=calc();
        if(cur<prv) memcpy(prvp,p,4*(n+2)),prv=cur;
        t*=0.999;
    }
}
